bab_selesai = 2
total_bab = 11

# Contoh penggunaan "and"
print(bab_selesai < 5 and total_bab > 6)
print(bab_selesai < 5 and total_bab < 6)
print(bab_selesai > 5 and total_bab < 6)

# Contoh penggunaan "or"
print(bab_selesai < 5 or total_bab > 6)
print(bab_selesai < 5 or total_bab < 6)
print(bab_selesai > 5 or total_bab < 6)

# Contoh penggunaan "not"
print(not(bab_selesai < 5 or total_bab > 6))
print(not(bab_selesai > 5 or total_bab < 6))
