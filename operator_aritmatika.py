total_bab = 11
bab_selesai = 2
file_per_bab = 3

# Penjumlahan
bab_berikutnya = bab_selesai + 1

# Pengurangan
bab_sisa = total_bab - bab_selesai

# Perkalian
file_dua_bab = file_per_bab * 2

# Pembagian
setengah_bab = total_bab / 2

# Modulus
sisa_bagi = total_bab % 2

# Eksponensial
kuadrat = bab_selesai ** 2

# Cetak output
print(bab_berikutnya)
print(bab_sisa)
print(file_dua_bab)
print(setengah_bab)
print(sisa_bagi)
print(kuadrat)
