# Membuat lists yang berisi nama-nama bab yang sudah dikerjakan
bab = ["Pengenalan", "Variabel", "Operator", "Kondisi"]

# Mengakses item berdasarkan urutannya (indexing), dimulai dari angka 0
print(bab[1])

# Negative indexing: -1 item terakhir, -2 item kedua dari belakang
print(bab[-1])
print(bab[-2])
